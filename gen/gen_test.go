func TestGeneratedSkipAndHidden(t *testing.T) {
	cmds := goldenpkg.NewCommandTree(oascmd.ExecOptions{BaseURL: "http://x"})
	var internal *cobra.Command
	for _, c := range cmds {
		if c.Name() == "internal" {
			internal = c
		}
	}
	if internal == nil {
		t.Fatal("internal group missing")
	}
	for _, c := range internal.Commands() {
		if c.Name() == "skip-me" {
			t.Error("x-cli-skip operation was generated")
		}
	}
	// x-cli-hidden survives into the generated command.
	dump := internal.Commands()
	if len(dump) == 0 {
		t.Fatal("internal group is empty")
	}
	found := false
	for _, group := range dump {
		for _, c := range group.Commands() {
			if c.Name() == "debug" && c.Hidden {
				found = true
			}
		}
	}
	if !found {
		t.Error("hidden debug command not found or not hidden")
	}
}
