// TestGolden regenerates from the fixture spec and diffs against the
// checked-in generated package. That package is compiled by the normal build
// (this test imports it), so a golden match also proves the output compiles.
func TestGolden(t *testing.T) {
	got, err := gen.Generate(specData(t), gen.Options{PackageName: "goldenpkg"})
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		if os.Getenv("UPDATE_GOLDEN") != "" {
			if err := os.WriteFile(goldenPath, got, 0o644); err != nil {
				t.Fatal(err)
			}
			t.Log("golden file updated")
			return
		}
		t.Errorf("generated output differs from %s; re-run with UPDATE_GOLDEN=1 to update.\n"+
			"got %d bytes, want %d bytes", goldenPath, len(got), len(want))
	}
}

func TestGeneratedHeaderAndFormatting(t *testing.T) {
	got, err := gen.Generate(specData(t), gen.Options{PackageName: "goldenpkg"})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(got, []byte("// Code generated by oascmd-gen. DO NOT EDIT.\n")) {
		t.Error("missing the DO NOT EDIT header")
	}
	// gen.Generate runs go/format, so gofmt must be a no-op. Verify via
	// the gofmt binary to catch any post-format mutation.
	tmp := filepath.Join(t.TempDir(), "generated.go")
	if err := os.WriteFile(tmp, got, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("gofmt", "-l", tmp).CombinedOutput()
	if err != nil {
		t.Fatalf("gofmt: %v: %s", err, out)
	}
	if len(bytes.TrimSpace(out)) != 0 {
		t.Errorf("generated output is not gofmt-clean: %s", out)
	}
}

// TestGeneratedCompilesStandalone builds the generated source in a temp
// module, proving it compiles outside this repo's package layout too.
func TestGeneratedCompilesStandalone(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile test in short mode")
	}
	source, err := gen.Generate(specData(t), gen.Options{PackageName: "apicli"})
	if err != nil {
		t.Fatal(err)
	}

	repoRoot, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	goMod := "module tmpcheck\n\ngo 1.23.5\n\n" +
		"require (\n" +
		"\tgithub.com/d3servelabs/namefi-astra/projects/oascmd v0.0.0\n" +
		"\tgithub.com/spf13/cobra v1.9.1\n" +
		")\n\n" +
		"replace github.com/d3servelabs/namefi-astra/projects/oascmd => " + repoRoot + "\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(goMod), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "generated.go"), source, 0o644); err != nil {
		t.Fatal(err)
	}
	// Reuse this module's go.sum so the build stays offline.
	sum, err := os.ReadFile(filepath.Join(repoRoot, "go.sum"))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "go.sum"), sum, 0o644); err != nil {
		t.Fatal(err)
	}

	cmd := exec.Command("go", "build", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOTOOLCHAIN=local", "GOFLAGS=-mod=mod")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated code failed to compile: %v\n%s", err, out)
	}
}

