func TestGeneratedTypes(t *testing.T) {
	// Compile-time proof that the emitted structs are usable and typed.
	pet := goldenpkg.Pet{
		ID:         "p1",
		Name:       "Rex",
		Age:        3,
		Vaccinated: true,
		Nicknames:  []string{"rexy"},
		Owner:      &goldenpkg.Owner{Name: "Ada"},
		Metadata:   json.RawMessage(`{"note":"good boy"}`),
	}
	encoded, err := json.Marshal(pet)
	if err != nil {
		t.Fatal(err)
	}
	var round map[string]any
	if err := json.Unmarshal(encoded, &round); err != nil {
		t.Fatal(err)
	}
	if round["id"] != "p1" || round["name"] != "Rex" {
		t.Errorf("json tags wrong: %s", encoded)
	}
	owner, ok := round["owner"].(map[string]any)
	if !ok || owner["name"] != "Ada" {
		t.Errorf("nested ref not encoded: %s", encoded)
	}
	// Optional empty fields are omitted.
	minimal, err := json.Marshal(goldenpkg.Owner{Name: "x"})
	if err != nil {
		t.Fatal(err)
	}
	if string(minimal) != `{"name":"x"}` {
		t.Errorf("omitempty not applied: %s", minimal)
	}
}

// TestGeneratedCommandExecution runs a generated command end to end against
// an httptest server: the buildtime path must produce the same request the
// runtime path does.
func TestGeneratedCommandExecution(t *testing.T) {
	var gotMethod, gotPath, gotQuery, gotAuth string
	var gotBody map[string]any
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotMethod, gotPath, gotQuery = r.Method, r.URL.Path, r.URL.RawQuery
		gotAuth = r.Header.Get("Authorization")
		_ = json.NewDecoder(r.Body).Decode(&gotBody)
		_, _ = w.Write([]byte(`{"ok":true}`))
	}))
	defer server.Close()

	var out bytes.Buffer
	execOpts := oascmd.ExecOptions{
		BaseURL: server.URL,
		Out:     &out,
		Auth: func(req *http.Request) error {
			req.Header.Set("Authorization", "Bearer gen")
			return nil
		},
	}
	root := &cobra.Command{Use: "test", SilenceUsage: true, SilenceErrors: true}
	for _, c := range goldenpkg.NewCommandTree(execOpts) {
		root.AddCommand(c)
	}
	root.SetOut(io.Discard)
	root.SetErr(io.Discard)

	// Query params, including the schema default and an array.
	root.SetArgs([]string{"pets", "list", "--status", "sold", "--tags", "a", "--tags", "b"})
	if err := root.ExecuteContext(context.Background()); err != nil {
		t.Fatal(err)
	}
	if gotMethod != "GET" || gotPath != "/pets" {
		t.Errorf("request = %s %s", gotMethod, gotPath)
	}
	if gotAuth != "Bearer gen" {
		t.Errorf("auth = %q", gotAuth)
	}
	for _, want := range []string{"limit=20", "status=sold", "tags=a", "tags=b"} {
		if !strings.Contains(gotQuery, want) {
			t.Errorf("query %q missing %q", gotQuery, want)
		}
	}
	if !strings.Contains(out.String(), `"ok": true`) {
		t.Errorf("output not pretty-printed: %q", out.String())
	}

	// Path parameter.
	root.SetArgs([]string{"pets", "get", "--pet-id", "p-7"})
	if err := root.ExecuteContext(context.Background()); err != nil {
		t.Fatal(err)
	}
	if gotPath != "/pets/p-7" {
		t.Errorf("path = %q, want /pets/p-7", gotPath)
	}

	// JSON body from per-property flags.
	gotBody = nil
	root.SetArgs([]string{"pets", "create", "--name", "Rex", "--age", "3", "--vaccinated"})
	if err := root.ExecuteContext(context.Background()); err != nil {
		t.Fatal(err)
	}
	if gotBody["name"] != "Rex" || gotBody["age"] != float64(3) || gotBody["vaccinated"] != true {
		t.Errorf("body = %+v", gotBody)
	}
}

