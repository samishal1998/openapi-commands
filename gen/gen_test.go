func TestGenerateOnEmitOperation(t *testing.T) {
	got, err := gen.Generate(specData(t), gen.Options{
		PackageName: "goldenpkg",
		OnEmitOperation: func(cmd *gen.CommandModel) error {
			if cmd.Op.ID == "listPets" {
				cmd.FuncName = "NewCustomListCommand"
			}
			if cmd.Op.ID == "debugDump" {
				return oascmd.SkipOperation
			}
			return nil
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(got, []byte("func NewCustomListCommand(")) {
		t.Error("OnEmitOperation rename did not take effect")
	}
	if bytes.Contains(got, []byte("NewInternalDumpDebugCommand")) {
		t.Error("OnEmitOperation veto did not drop the command")
	}
}

